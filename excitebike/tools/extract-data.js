/* Writes reference/data.gen.js: the DATA bytes of the Excitebike ROM (tables,
   track layouts, obstacle scripts, screen layouts, metasprite tables...) and
   the 8 KB CHR ROM (all of the game's graphics), for embedding in index.html.

   Only bytes the BZK listing marks as data ("- D" lines) or that it lists
   as .byte/.word/.dbyt are taken; CODE bytes are left out (zero), because
   the game logic is re-written in JavaScript, not executed.

     node tools/extract-data.js && node tools/inject.js
*/
const fs = require('fs');
const path = require('path');
const { chr } = require('./rom.js');

const src = fs.readFileSync(path.join(__dirname, '..', 'reference', 'disasm', 'bank_FF.asm'), 'utf8').split(/\r?\n/);
const re = /^(.) (.) (.) (.) (.) (.) 0x00([0-9A-F]{4}) 00:([0-9A-F]{4}): ((?:[0-9A-F]{2} ){1,3})\s*(\S+)/;
const data = new Uint8Array(0x4000), have = new Uint8Array(0x4000);
let nData = 0;
for (const line of src) {
  const m = re.exec(line); if (!m) continue;
  const isCode = m[1] === 'C';
  const isDataDirective = /^\.(byte|word|dbyt)$/.test(m[10]);
  if (isCode || (m[2] !== 'D' && !isDataDirective)) continue;
  const addr = parseInt(m[8], 16) - 0xC000;
  let bytes = m[9].trim().split(' ').map(h => parseInt(h, 16));
  const mb = /\.byte\s+([^;]+)/.exec(line);
  if (mb && mb[1].indexOf(',') >= 0) bytes = mb[1].split(',').map(v => parseInt(v.trim().slice(1), 16));
  bytes.forEach((b, i) => { data[addr + i] = b; have[addr + i] = 1; nData++; });
}
// merge into ranges (gaps of <= 4 code bytes are bridged with zeros to keep the list short)
const ranges = [];
let i = 0;
while (i < 0x4000) {
  if (!have[i]) { i++; continue; }
  let j = i;
  for (;;) {
    while (j < 0x4000 && have[j]) j++;
    let k = j; while (k < 0x4000 && !have[k] && k - j < 4) k++;
    if (k < 0x4000 && have[k] && k - j < 4) { j = k; continue; }
    break;
  }
  ranges.push([0xC000 + i, Buffer.from(data.slice(i, j)).toString('base64')]);
  i = j;
}
const out = '/* generated by tools/extract-data.js from the Excitebike ROM data bytes (' + nData + ' bytes) and CHR ROM - do not edit */\n' +
  'const ROMDATA = ' + JSON.stringify(ranges) + ';\n' +
  'const CHR_B64 = "' + Buffer.from(chr).toString('base64') + '";';
fs.writeFileSync(path.join(__dirname, '..', 'reference', 'data.gen.js'), out);
console.log('data bytes', nData, 'ranges', ranges.length, 'file', out.length, 'chars');

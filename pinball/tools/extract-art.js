/* Extracts the genuine NES Pinball graphics by RUNNING the ROM (rebuilt
   byte-exact from reference/disasm/pinball.asm by tools/rom.js) in the
   offline emulator (tools/nes.js) and recording what it draws:

     - the 8 KB CHR ROM (every tile: tables, ball, flippers, penguins, chicks,
       seals, cards, Mario, Pauline, font, title logo)
     - the nametable + attribute table + palette of the title screen, the
       upper table (scene A), the lower table (scene B) and the bonus stage
     - the background patches the ROM writes for events (cards face up)

   Sprite layouts (which tiles make the flippers, eggs, Mario...) are small
   tables in index.html; they were read from OAM captures with the same
   emulator (see CLAUDE.md "Art").  Output: reference/art.gen.js, spliced into
   index.html by tools/inject.js.

     node tools/extract-art.js     (then node tools/inject.js)            */
'use strict';
const fs = require('fs');
const path = require('path');
const { NES } = require('./nes.js');
const { NES_PAL, renderNES, savePNG } = require('./ppu-render.js');

const OUT = path.join(__dirname, '..', 'reference', 'art.gen.js');
const SHOTS = path.join(__dirname, 'out');
if (!fs.existsSync(SHOTS)) fs.mkdirSync(SHOTS);

function place(n, x, y) {
  n.ram[0x16] = x; n.ram[0x15] = 0; n.ram[0x18] = y; n.ram[0x17] = 0;
  for (const a of [0x0A, 0x0B, 0x0C, 0x0D, 0x19, 0x1A]) n.ram[a] = 0;
}
function boot(launch) {
  const n = new NES();
  n.run(120);
  if (launch === undefined) return n;
  n.run(5, NES.BTN.start); n.run(400, 0);
  if (launch) { n.run(25, NES.BTN.a); n.run(40, 0); }
  return n;
}
function screen(n) {
  const nt = Uint8Array.from(n.vram.slice(0, 0x400));
  return { nt: Buffer.from(nt).toString('base64'), pal: Array.from(n.pal), ctrl: n.ppuctrl };
}

const art = {};
const report = [];

/* ---- title ---- */
{
  const n = boot();
  art.title = screen(n);
  savePNG(path.join(SHOTS, 'rom-title.png'), renderNES(n), 2);
  report.push('title ctrl=' + n.ppuctrl.toString(16));
}
/* ---- upper table (scene A): launch, ball in the shooter lane above ---- */
{
  const n = boot(true); n.run(30, 0);
  if (n.ram[0xBF] !== 0) throw new Error('expected upper table');
  art.upper = screen(n);
  savePNG(path.join(SHOTS, 'rom-upper.png'), renderNES(n), 2);
}
/* ---- lower table (scene B): ball drained from the upper table ---- */
let lowerBase;
{
  const n = boot(true);
  for (let i = 0; i < 3000 && n.ram[0xBF] !== 1; i++) n.runFrame();
  n.run(20, 0); place(n, 150, 100); n.run(2, 0);
  if (n.ram[0xBF] !== 1) throw new Error('expected lower table');
  art.lower = screen(n);
  lowerBase = n;
  savePNG(path.join(SHOTS, 'rom-lower.png'), renderNES(n), 2);
}
/* ---- card face-up patches: drop the ball through each card lane ---- */
{
  art.cards = [];
  for (let k = 0; k < 5; k++) {
    const n = Object.create(Object.getPrototypeOf(lowerBase));
    Object.assign(n, lowerBase);
    // (shallow clone: copy the byte arrays and the CPU)
    n.ram = lowerBase.ram.slice(); n.vram = lowerBase.vram.slice(); n.pal = lowerBase.pal.slice(); n.oam = lowerBase.oam.slice();
    n.pad = [0, 0]; n.padShift = [0, 0]; n.apuLog = [];
    const c = Object.create(Object.getPrototypeOf(lowerBase.cpu)); Object.assign(c, lowerBase.cpu);
    c.read = a => n.read(a); c.write = (a, v) => n.write(a, v); n.cpu = c;
    const v0 = n.vram.slice();
    place(n, 112 + 16 * k, 44); n.run(30, 0);
    const patch = [];
    for (let i = 0x40; i < 0xC0; i++) if (v0[i] !== n.vram[i] && (i & 31) > 8) patch.push([i, n.vram[i]]);
    if (patch.length !== 6) throw new Error('card ' + k + ' patch has ' + patch.length + ' tiles');
    art.cards.push(patch);
  }
  report.push('cards: 5 x 6 tiles');
}
/* ---- bonus stage: put the ball in the lower table's hole ---- */
{
  const n = boot(false); n.run(3, NES.BTN.a); n.run(1, 0); place(n, 207, 31);
  for (let i = 0; i < 400 && n.ram[0xBF] !== 2; i++) n.runFrame();
  n.run(40, 0);
  if (n.ram[0xBF] !== 2) throw new Error('expected bonus stage');
  art.bonus = screen(n);
  savePNG(path.join(SHOTS, 'rom-bonus.png'), renderNES(n), 2);
}

art.chr = Buffer.from(new NES().chr).toString('base64');
art.nespal = NES_PAL;

const body = '/* generated by tools/extract-art.js from the Pinball ROM rebuilt from reference/disasm/pinball.asm - do not edit */\n' +
  'const ART = ' + JSON.stringify(art) + ';';
fs.writeFileSync(OUT, body);
console.log(report.join('\n'));
console.log('wrote ' + OUT + ' (' + body.length + ' bytes)');
